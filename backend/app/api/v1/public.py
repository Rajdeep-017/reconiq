"""Public landing-page endpoints.

These endpoints are intentionally unauthenticated and must never expose tenant
data. The landing page renders an explicitly labelled product demonstration
whose values are controlled by the backend, not by the frontend.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Literal

from fastapi import APIRouter
from pydantic import BaseModel

router = APIRouter(prefix="/public", tags=["Public"])


class PublicTrendPoint(BaseModel):
    label: str
    matched: int
    pending: int


class PublicOverviewCounts(BaseModel):
    total_transactions: int
    matched_transactions: int
    pending_transactions: int
    matching_rate: float
    reconciliation_status: str


class PublicMatchBreakdown(BaseModel):
    label: str
    count: int


class PublicSettlementPreview(BaseModel):
    settlement_amount: float
    expected_amount: float
    actual_amount: float
    difference: float
    status: str
    processing_state: str


class PublicDiscrepancyCategory(BaseModel):
    category: str
    count: int


class PublicDiscrepancyPreview(BaseModel):
    open: int
    under_review: int
    resolved: int
    categories: list[PublicDiscrepancyCategory]


class PublicClaimPreview(BaseModel):
    total: int
    draft: int
    submitted: int
    under_review: int
    resolved: int
    recovered_amount: float


class PublicOverview(BaseModel):
    mode: Literal["demo"]
    disclaimer: str
    generated_at: datetime
    overview: PublicOverviewCounts
    trend: list[PublicTrendPoint]
    matching_breakdown: list[PublicMatchBreakdown]
    settlement: PublicSettlementPreview
    discrepancies: PublicDiscrepancyPreview
    claims: PublicClaimPreview


# Deliberate, backend-owned demonstration dataset. The frontend never invents
# or hardcodes these values. Keep the arithmetic internally consistent so the
# preview behaves like the real product without presenting customer data.
_DEMO_TREND = [
    PublicTrendPoint(label="Mon", matched=23_840, pending=1_610),
    PublicTrendPoint(label="Tue", matched=24_610, pending=1_520),
    PublicTrendPoint(label="Wed", matched=24_120, pending=1_780),
    PublicTrendPoint(label="Thu", matched=24_980, pending=1_490),
    PublicTrendPoint(label="Fri", matched=25_140, pending=1_620),
    PublicTrendPoint(label="Sat", matched=23_620, pending=1_980),
    PublicTrendPoint(label="Sun", matched=25_532, pending=2_418),
]

_DEMO_CATEGORIES = [
    PublicDiscrepancyCategory(category="Short payment", count=64),
    PublicDiscrepancyCategory(category="Missing settlement", count=28),
    PublicDiscrepancyCategory(category="COD remittance", count=21),
    PublicDiscrepancyCategory(category="Freight overcharge", count=19),
    PublicDiscrepancyCategory(category="Return / refund", count=16),
]


@router.get("/overview", response_model=PublicOverview)
def get_public_overview() -> PublicOverview:
    """Return the landing-page demonstration dataset.

    No database session is used. The response is public, contains only
    aggregate demonstration values, and is explicitly labelled as demo data.
    """
    matched = sum(point.matched for point in _DEMO_TREND)
    pending = sum(point.pending for point in _DEMO_TREND)
    total = matched + pending

    return PublicOverview(
        mode="demo",
        disclaimer=(
            "Illustrative product demonstration. Values are generated by the "
            "ReconIQ demo endpoint and are not live customer data."
        ),
        generated_at=datetime.now(timezone.utc),
        overview=PublicOverviewCounts(
            total_transactions=total,
            matched_transactions=matched,
            pending_transactions=pending,
            matching_rate=round(matched / total * 100, 2),
            reconciliation_status="Reconciliation healthy",
        ),
        trend=_DEMO_TREND,
        matching_breakdown=[
            PublicMatchBreakdown(label="Exact matches", count=164_210),
            PublicMatchBreakdown(label="Assisted matches", count=7_632),
            PublicMatchBreakdown(label="Unmatched", count=12_418),
        ],
        settlement=PublicSettlementPreview(
            settlement_amount=4_804_120.00,
            expected_amount=4_862_400.00,
            actual_amount=4_804_120.00,
            difference=-58_280.00,
            status="Review required",
            processing_state="Completed",
        ),
        discrepancies=PublicDiscrepancyPreview(
            open=sum(category.count for category in _DEMO_CATEGORIES),
            under_review=32,
            resolved=412,
            categories=_DEMO_CATEGORIES,
        ),
        claims=PublicClaimPreview(
            total=76,
            draft=14,
            submitted=18,
            under_review=21,
            resolved=23,
            recovered_amount=1_284_500.00,
        ),
    )
